test('delivery retention defaults and Agent override preserve drafts and save on existing routes',async({page})=>{
 const f=await settingsFixture()
 try{
  await page.goto(f.url+'/#/settings/agents')
  const globalCount=page.getByRole('spinbutton',{name:'交付版本保留数量',exact:true}),override=page.getByRole('spinbutton',{name:'交付版本保留数量（覆盖）',exact:true})
  await expect(globalCount).toHaveValue('10');await globalCount.fill('3')
  await page.getByRole('link',{name:'编辑 root',exact:true}).click();await page.getByRole('link',{name:'Tuck 工具',exact:true}).click()
  await expect(override).toHaveValue('');await expect(override).toHaveAttribute('placeholder','跟随全局（3）')
  await override.fill('0');await expect(page.getByText(/每个对话保留最新 1 个版本/)).toBeVisible()
  await page.getByRole('link',{name:'返回 Agent 配置',exact:true}).click();await page.getByRole('link',{name:'返回 Agent 列表',exact:true}).click();await expect(globalCount).toHaveValue('3')
  await page.getByRole('button',{name:'保存并生效',exact:true}).click();await expect(page.getByRole('status')).toHaveText('已保存并生效')
  await page.reload();await expect(globalCount).toHaveValue('3')
  await page.goto(f.url+'/#/settings/agents/root/tools/tuck');await expect(override).toHaveValue('0')
  await override.fill('');await expect(override).toHaveValue('');await expect(page.getByText(/每个对话保留最新 3 个版本/)).toBeVisible()
  await page.getByRole('button',{name:'保存并生效',exact:true}).click();await expect(page.getByRole('status')).toHaveText('已保存并生效');await expect(page).toHaveURL(/\/tools\/tuck$/)
  await page.reload();await expect(override).toHaveValue('')
  const saved=await f.read();expect(saved.config.workbench.deliveryRetentionCount).toBe(3);expect(saved.config.workbench.assistants.find((a:any)=>a.agent==='root').deliveryRetentionCount).toBeUndefined()
  await override.fill('101');await page.getByRole('button',{name:'保存并生效',exact:true}).click();await expect(page.getByRole('alert')).toBeVisible();expect((await f.read()).revision).toBe(saved.revision)
 }finally{await f.close()}
})

