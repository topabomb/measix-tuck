test('a failed first text read disables save-as and a failed reread keeps draft download available',async({page})=>{
  core.put('failed-read.txt','original important content')
  let reject=true
  await page.route('**/api/enterprise-workspace/content?*',async route=>{
    const request=route.request(),url=new URL(request.url())
    if(reject&&request.method()==='GET'&&url.searchParams.get('path')==='failed-read.txt')await route.fulfill({status:503,json:{error:'fixture content read failed'}})
    else await route.continue()
  })
  const {panel}=await open(page,'failed-read.txt')
  await expect(panel.getByRole('alert')).toContainText('fixture content read failed')
  await expect(panel.getByRole('button',{name:'另存草稿',exact:true})).toBeDisabled()
  reject=false
  await panel.getByRole('button',{name:'文档操作',exact:true}).click()
  await panel.getByRole('button',{name:'重新读取',exact:true}).click()
  await expect(panel.locator('.cm-content')).toContainText('original important content')
  await panel.locator('.cm-content').fill('draft remains downloadable')
  reject=true
  await panel.getByRole('button',{name:'文档操作',exact:true}).click()
  await panel.getByRole('button',{name:'重新读取',exact:true}).click()
  await page.getByRole('dialog',{name:'丢弃当前未保存修改并读取远端版本？',exact:true}).getByRole('button',{name:'确定',exact:true}).click()
  await expect(panel.getByRole('alert')).toContainText('fixture content read failed')
  await expect(panel.getByRole('button',{name:'另存草稿',exact:true})).toBeDisabled()
  await expect(panel.getByRole('button',{name:'下载草稿',exact:true})).toBeEnabled()
  const download=page.waitForEvent('download')
  await panel.getByRole('button',{name:'下载草稿',exact:true}).click()
  const stream=await (await download).createReadStream(),chunks:Buffer[]=[]
  for await(const chunk of stream!)chunks.push(Buffer.from(chunk))
  expect(Buffer.concat(chunks).toString()).toBe('draft remains downloadable')
  expect(core.files.get('failed-read.txt')?.toString()).toBe('original important content')
  expect(core.requests.some(request=>request.method==='PUT')).toBe(false)
})
