test('Tuck switches persist and theme menu applies immediately without saving the draft',async({page},info)=>{
 const f=await settingsFixture()
 try{
  await page.goto(f.url+'/#/settings/agents/root/tools/tuck')
  for(const name of ['启用查看会话','启用发送会话消息','启用上传工作区文件','启用批量下载工作区文件'])await page.getByRole('checkbox',{name,exact:true}).uncheck()
  await page.getByRole('button',{name:'保存并生效',exact:true}).click();await expect(page.getByRole('status')).toHaveText('已保存并生效')
  await page.reload();await expect(page.getByRole('checkbox',{name:'启用上传工作区文件',exact:true})).not.toBeChecked()
  await page.getByRole('checkbox',{name:'启用上传工作区文件',exact:true}).check()
  const before=(await f.read()).revision,url=page.url()
  await page.getByTestId('mode-settings').click()
  const menu=page.getByRole('navigation',{name:'设置快捷菜单'})
  await menu.getByRole('button',{name:'主题',exact:true}).click()
  await menu.getByRole('button',{name:'石墨',exact:true}).click()
  await expect(page.locator('html')).toHaveAttribute('data-tuck-theme','graphite')
  expect(page.url()).toBe(url);expect((await f.read()).revision).toBe(before)
  await expect(page.getByRole('checkbox',{name:'启用上传工作区文件',exact:true})).toBeChecked()
  for (const width of [320,390]) {
    await page.setViewportSize({width,height:780})
    await expect(page.getByTestId('mode-settings')).toHaveCount(0)
    const more=page.getByRole('button',{name:'更多频道与设置',exact:true})
    await more.click();await menu.getByRole('button',{name:'主题',exact:true}).click()
    await expect(menu).toBeInViewport({ratio:1})
    await page.screenshot({path:info.outputPath(`tuck-tools-theme-${width}.png`)})
    await menu.getByRole('button',{name:'墨蓝',exact:true}).click()
    expect(page.url()).toBe(url);expect((await f.read()).revision).toBe(before)
    await expect(page.getByRole('checkbox',{name:'启用上传工作区文件',exact:true})).toBeChecked()
    await menu.getByRole('button',{name:'墨蓝',exact:true}).press('Escape')
    await expect(menu).toHaveCount(0);await expect(more).toBeFocused()
    await more.click();await menu.getByRole('link',{name:'设置',exact:true}).click();await expect(menu).toHaveCount(0)
  }
 }finally{await f.close()}
})
