import {expect,test} from '@playwright/test'
import {readFile,writeFile,access} from 'node:fs/promises'
import {join} from 'node:path'
import {fixture,until} from '../../tests/fixtures/fixture.mjs'

for(const width of [1365,390])test(`confirmed delete preserves independent fork and shared files at ${width}px`,async({page,context},info)=>{
  const app=await fixture({delivery:true})
  const errors:string[]=[]
  page.on('pageerror',error=>errors.push(error.message))
  try {
    const task=await app.manager.create({title:'删除范围验证',approvalMode:'auto'})
    app.manager.submit(task.id,'FULL_LOOP')
    await until(()=>app.manager.get(task.id).pendingInteraction?.kind==='question')
    const question=app.manager.get(task.id).pendingInteraction!
    const answered=await page.request.post(`${app.url}/api/tasks/${task.id}/interaction`,{data:{interactionId:question.id,kind:'question',answer:'删除验证报告'}})
    expect(answered.ok()).toBe(true)
    await until(()=>app.manager.get(task.id).lastTurnReason==='completed'&&!app.manager.runs.has(task.id))
    const children=app.request({op:'tasks'}).filter((value:any)=>value.parentTaskId===task.id)
    expect(children.length).toBeGreaterThan(0)
    const source=join(task.workspace,'shared.txt')
    await writeFile(source,'shared original')
    await app.deliver(task,'交付副本',['shared.txt'])
    const delivery=(await (await page.request.get(`${app.url}/api/tasks/${task.id}/deliveries/latest`)).json())
    const snapshot=join(app.directory,'data','deliveries','snapshots',task.id,delivery.id)
    await access(snapshot)
    const post=async(path:string,data:unknown)=>(await page.request.post(app.url+path,{data})).json()
    const forked=await post(`/api/tasks/${task.id}/fork`,{index:0})
    expect(forked.task.id).toBeTruthy()
    expect(forked.task.workspace).toBe(task.workspace)
    await post(`/api/tasks/${forked.task.id}/rename`,{title:'保留的独立分支'})
    const notConfirmed=await page.request.post(`${app.url}/api/tasks/${task.id}/delete`,{data:{}})
    expect(notConfirmed.status()).toBe(400)
    await page.setViewportSize({width,height:844})
    const other=await context.newPage()
    other.on('pageerror',error=>errors.push(error.message))
    await other.goto(`${app.url}/#/chat/conversations/${task.id}`)
    await expect(other.getByTestId('session-menu')).toBeVisible()
    await page.goto(`${app.url}/#/chat/conversations/${task.id}`)
    await page.getByTestId('session-menu').click()
    await page.getByTestId('task-delete').click()
    const dialog=page.getByRole('dialog',{name:'删除对话',exact:true})
    await expect(dialog).toContainText('独立分支、工作目录、上传源文件及共享文件会保留')
    await expect(dialog.getByRole('button',{name:'取消',exact:true})).toBeFocused()
    await page.screenshot({path:info.outputPath(`delete-confirm-${width}.png`)})
    await dialog.getByRole('button',{name:'取消',exact:true}).click()
    expect((await page.request.get(`${app.url}/api/tasks/${task.id}`)).status()).toBe(200)
    await page.getByTestId('session-menu').click()
    await page.getByTestId('task-delete').click()
    await dialog.getByRole('button',{name:'确认删除',exact:true}).click()
    await expect(page).toHaveURL(new RegExp(forked.task.id))
    await expect(other).toHaveURL(new RegExp(forked.task.id))
    await expect(dialog).toHaveCount(0)
    expect((await page.request.get(`${app.url}/api/tasks/${task.id}`)).status()).toBe(404)
    for(const child of children)expect((await page.request.get(`${app.url}/api/tasks/${child.id}`)).status()).toBe(404)
    for(const child of children)await expect(app.docker.request(`/api/sessions/${child.nativeSessionId}`)).rejects.toThrow()
    await expect(app.docker.request(`/api/sessions/${task.nativeSessionId}`)).rejects.toThrow()
    expect(await app.docker.request(`/api/sessions/${forked.task.nativeSessionId}`)).toHaveProperty('id',forked.task.nativeSessionId)
    expect(await readFile(source,'utf8')).toBe('shared original')
    await expect(access(snapshot)).rejects.toThrow()
    const continued=await page.request.post(`${app.url}/api/tasks/${forked.task.id}/prompts`,{data:{prompt:'继续独立分支'}})
    expect(continued.status()).toBe(202)
    await until(()=>app.manager.get(forked.task.id).lastTurnReason==='completed'&&!app.manager.runs.has(forked.task.id))
    await page.reload()
    await expect(page.getByTestId('session-menu')).toBeVisible()
    expect(await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth)).toBeLessThanOrEqual(1)
    expect(errors.filter(message=>!message.includes('ResizeObserver'))).toEqual([])
    await other.close()
  }finally{await app.close()}
})

test('busy deletion stays in confirmation dialog; archived and task-channel entries delete explicitly',async({page})=>{
  const app=await fixture()
  try {
    const task=await app.manager.create({title:'审批保护',approvalMode:'manual'})
    app.manager.submit(task.id,'REJECT_ONLY')
    await until(()=>app.manager.get(task.id).pendingInteraction?.kind==='approval')
    const approval=app.manager.get(task.id).pendingInteraction!.id
    await page.goto(`${app.url}/#/chat/conversations/${task.id}`)
    await page.getByTestId('session-menu').click()
    await page.getByTestId('task-delete').click()
    const dialog=page.getByRole('dialog',{name:'删除对话',exact:true})
    await dialog.getByRole('button',{name:'确认删除',exact:true}).click()
    await expect(dialog.getByRole('alert')).toContainText('处理审批')
    expect(app.manager.get(task.id).pendingInteraction!.id).toBe(approval)
    await dialog.getByRole('button',{name:'取消',exact:true}).click()
    const archived=await app.manager.create({title:'归档删除'})
    await page.request.post(`${app.url}/api/tasks/${archived.id}/archive`,{data:{archived:true}})
    await page.locator('.archived-sessions > summary').click()
    await page.getByRole('button',{name:'删除 归档删除',exact:true}).click()
    await dialog.getByRole('button',{name:'确认删除',exact:true}).click()
    await expect(dialog).toHaveCount(0)
    expect(app.manager.get(task.id).pendingInteraction!.id).toBe(approval)
    const channel=await app.manager.create({title:'T-1234 · 可删除任务'})
    await page.goto(`${app.url}/#/tasks/${channel.id}`)
    await page.getByTestId('task-delete').click()
    await dialog.getByRole('button',{name:'确认删除',exact:true}).click()
    await expect(page).toHaveURL(/#\/tasks$/)
  }finally{await app.close()}
})
