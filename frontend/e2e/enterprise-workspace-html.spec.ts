test('full HTML preserves document styles and renders before local images complete without resetting scroll',async({page})=>{
  blockedImage=new Promise(resolve=>{releaseImage=resolve})
  core.put('slow.png',core.files.get('sample.png')!)
  core.put('local.css','body.document {color:rgb(24, 36, 48)} #styled {font-size:23px} @import "https://bad.invalid/import.css"; .remote {background:url(https://bad.invalid/css.png)}')
  core.put('full.html','<!doctype html><html lang="zh-CN" class="report"><head><title>完整文档</title><style>body {background:rgb(240, 241, 242);margin:0} h1 {color:rgb(17, 34, 51)}</style><link rel="stylesheet" href="local.css"></head><body class="document" style="padding:31px" dir="ltr"><h1 id="styled">完整页面先显示</h1><div style="height:1800px">正文</div><img id="slow" alt="原始图片说明" src="slow.png"><p id="end">结尾</p></body></html>')
  const external:string[]=[];page.on('request',request=>{if(request.url().includes('bad.invalid'))external.push(request.url())})
  const {panel,frame}=await open(page,'full.html')
  await expect(frame.locator('h1')).toHaveText('完整页面先显示')
  await expect(frame.locator('html')).toHaveAttribute('lang','zh-CN')
  await expect(frame.locator('html')).toHaveClass('report')
  await expect(frame.locator('body')).toHaveClass('document')
  await expect(frame.locator('body')).toHaveCSS('padding','31px')
  await expect(frame.locator('body')).toHaveCSS('background-color','rgb(240, 241, 242)')
  await expect(frame.locator('body')).toHaveCSS('color','rgb(24, 36, 48)')
  await expect(frame.locator('h1')).toHaveCSS('font-size','23px')
  await expect(frame.locator('h1')).toHaveCSS('color','rgb(17, 34, 51)')
  await expect(frame.locator('#slow')).toHaveAttribute('alt','原始图片说明')
  expect(gets('slow.png')).toHaveLength(0)
  await frame.locator('#slow').scrollIntoViewIfNeeded()
  await expect.poll(()=>gets('slow.png').length).toBe(1)
  await frame.locator('body').evaluate(node=>{node.ownerDocument.defaultView!.scrollTo(0,650);(node as HTMLElement).dataset.sentinel='same-document'})
  releaseImage!()
  await expect.poll(()=>frame.locator('#slow').evaluate(node=>(node as HTMLImageElement).naturalWidth)).toBe(2)
  await expect(frame.locator('body')).toHaveAttribute('data-sentinel','same-document')
  expect(await frame.locator('body').evaluate(node=>node.ownerDocument.defaultView!.scrollY)).toBe(650)
  await expect(panel.getByText(/正在加载预览资源/)).toHaveCount(0)
  expect(gets('local.css')).toHaveLength(1)
  expect(external).toEqual([])
})

