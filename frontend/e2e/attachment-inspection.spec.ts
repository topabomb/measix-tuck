import {test,expect} from '@playwright/test'
import {fixture} from '../../tests/fixtures/fixture.mjs'
import {mkdir,unlink} from 'node:fs/promises'
import {resolve} from 'node:path'

test('vision defaults, Agent override and text-only conversation inspection work in the browser',async({page})=>{
 test.setTimeout(120000);page.setDefaultTimeout(15000)
 const app=await fixture({attachmentInspection:true,inspectionText:'识别证据：图片包含蓝色背景和金色方块。\n\n### 核对结果\n\n1. **背景**：蓝色。\n2. **主体**：金色方块。'})
 const screenshots=resolve('../.local/attachment-inspection')
 await mkdir(screenshots,{recursive:true})
 try{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto(app.url+'/#/settings/providers')
  await page.getByRole('combobox',{name:'默认识图模型',exact:true}).selectOption('vision')
  await page.getByRole('button',{name:'保存并生效',exact:true}).click()
  await expect(page.getByRole('status')).toContainText('已保存并生效')
  await page.reload()
  await expect(page.getByRole('combobox',{name:'默认识图模型',exact:true})).toHaveValue('vision')
  // Vision-only models are not offered as conversation models.
  await expect(page.getByLabel('默认模型（可选）').locator('option[value="vision"]')).toHaveCount(0)
  await page.goto(app.url+'/#/settings/agents/root/tools/tuck')
  await expect(page.getByRole('checkbox',{name:'启用识别附件',exact:true})).toBeChecked()
  await expect(page.getByRole('combobox',{name:'识图模型（覆盖）',exact:true})).toHaveValue('')
  await expect(page.getByRole('combobox',{name:'识图模型（覆盖）',exact:true}).locator('option:checked')).toHaveText('跟随全局默认')
  await page.getByRole('combobox',{name:'识图模型（覆盖）',exact:true}).selectOption('vision-alt')
  await page.getByRole('button',{name:'保存并生效',exact:true}).click()
  await expect(page.getByRole('status')).toContainText('已保存并生效')
  await page.reload()
  await expect(page.getByRole('combobox',{name:'识图模型（覆盖）',exact:true})).toHaveValue('vision-alt')
  for(const width of [1365,390,320]){
   await page.setViewportSize({width,height:900})
   await page.getByRole('combobox',{name:'识图模型（覆盖）',exact:true}).scrollIntoViewIfNeeded()
   await page.screenshot({path:resolve(screenshots,`agent-settings-${width}.png`)})
   expect(await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth)).toBeLessThanOrEqual(1)
  }
  const image=await page.evaluate(()=>{const c=document.createElement('canvas');c.width=640;c.height=400;const x=c.getContext('2d')!;x.fillStyle='#15375d';x.fillRect(0,0,640,400);x.fillStyle='#e5b65b';x.fillRect(220,110,200,180);return c.toDataURL('image/png').split(',')[1]!})
  const task=await app.manager.create({title:'纯文本助手识别图片',approvalMode:'auto'})
  await page.goto(app.url+`/#/chat/conversations/${task.id}`)
  await page.getByTestId('attachment-input').setInputFiles({name:'inspection.png',mimeType:'image/png',buffer:Buffer.from(image,'base64')})
  await expect(page.locator('.draft-attachment[data-status=ready]')).toHaveCount(1)
  await expect(page.getByText('图片路径将交给助手，由附件识别工具按需读取；聊天模型不会直接收到图片。')).toBeVisible()
  await page.getByTestId('composer-input').fill('INSPECT_TOOL 请识别这张图片。')
  await expect(page.getByTestId('send-message')).toBeEnabled()
  await page.getByTestId('send-message').click()
  await expect(page.getByText('已根据识图结果确认：蓝色背景，金色方块。',{exact:true})).toBeVisible({timeout:60000})
  const vision=app.requests.filter(r=>r.stream===false)
  expect(vision).toHaveLength(1);expect(vision[0]!.model).toBe('vision-alt')
  expect(JSON.stringify(vision[0])).toContain('data:image/')
  expect(JSON.stringify(vision[0])).not.toContain('INSPECT_TOOL')
  expect(vision[0]).not.toHaveProperty('tools')
  const chat=app.requests.filter(r=>r.stream===true)
  expect(chat.every(r=>!JSON.stringify(r).includes('data:image/'))).toBe(true)
  expect(JSON.stringify(chat)).toContain('识别证据：图片包含蓝色背景和金色方块。')
  const inputTool=page.getByTestId('tool-block').filter({has:page.locator('.activity-summary strong',{hasText:'inspect_attachments'})}).first()
  await inputTool.locator('.activity-summary').click()
  await expect(inputTool.getByText('识别输入 · 当前文件预览')).toBeVisible()
  await expect(inputTool.getByTestId('attachment-image')).toHaveCount(1)
  await expect.poll(()=>inputTool.locator('img').evaluate((img:HTMLImageElement)=>img.naturalWidth)).toBeGreaterThan(0)
  for(const width of [1365,390,320]){
   await page.setViewportSize({width,height:900})
   await inputTool.scrollIntoViewIfNeeded()
   await page.screenshot({path:resolve(screenshots,`tool-input-${width}.png`)})
   await inputTool.getByTestId('attachment-image').click()
   await expect(page.locator('.media-preview-dialog img')).toBeVisible()
   await page.screenshot({path:resolve(screenshots,`tool-input-preview-${width}.png`)})
   await page.getByRole('button',{name:'关闭图片预览'}).click()
   await page.getByTestId('attachment-image').first().click()
   await expect(page.locator('.media-preview-dialog img')).toBeVisible()
   await page.screenshot({path:resolve(screenshots,`upload-preview-${width}.png`)})
   await page.getByRole('button',{name:'关闭图片预览'}).click()
   await page.screenshot({path:resolve(screenshots,`conversation-${width}.png`)})
   expect(await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth)).toBeLessThanOrEqual(1)
  }
  const resultTool=page.getByTestId('tool-block').filter({has:page.locator('.activity-summary strong',{hasText:'inspect_attachments'})}).nth(1)
  await resultTool.locator('.activity-summary').click()
  await expect(resultTool.getByTestId('inspection-result-text').getByRole('heading',{name:'核对结果'})).toBeVisible()
  await expect(resultTool.getByTestId('inspection-result-text').locator('li')).toHaveCount(2)
  await expect(resultTool.locator('.result-details')).not.toHaveAttribute('open','')
  for(const width of [1365,390,320]){
   await page.setViewportSize({width,height:900})
   await resultTool.scrollIntoViewIfNeeded()
   await expect(resultTool.getByTestId('inspection-result-text')).toBeVisible()
   await page.screenshot({path:resolve(screenshots,`tool-result-${width}.png`)})
   expect(await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth)).toBeLessThanOrEqual(1)
  }
  await page.reload()
  await expect(page.getByText('已根据识图结果确认：蓝色背景，金色方块。',{exact:true})).toBeVisible()
  if(await inputTool.locator('.activity-summary').getAttribute('aria-expanded')==='false')await inputTool.locator('.activity-summary').click()
  await expect.poll(()=>inputTool.locator('img').evaluate((img:HTMLImageElement)=>img.naturalWidth)).toBeGreaterThan(0)
  await page.getByTestId('attachment-input').setInputFiles({name:'reject.png',mimeType:'image/png',buffer:Buffer.from(image,'base64')})
  await expect(page.locator('.draft-attachment[data-status=ready]')).toHaveCount(1)
  await page.getByTestId('composer-input').fill('INSPECT_TOOL REJECT_INSPECTION 请检查服务拒绝时的提示。')
  await page.getByTestId('send-message').click()
  await expect(page.getByText('识图模型拒绝了图片输入，请检查识图模型配置。',{exact:true})).toBeVisible({timeout:60000})
  expect(app.requests.filter(r=>r.stream===false)).toHaveLength(2)
  const failure=page.getByTestId('tool-block').filter({has:page.locator('.activity-summary strong',{hasText:'inspect_attachments'})}).last()
  await failure.locator('.activity-summary').click()
  await expect(failure.getByTestId('tool-failure-message')).toContainText('upstream_rejected')
  await expect(failure.getByTestId('tool-failure-message')).toBeVisible()
  await failure.scrollIntoViewIfNeeded()
  await page.screenshot({path:resolve(screenshots,'failure-320.png')})
  await page.goto(app.url+'/#/settings/agents/root/tools/tuck')
  await page.getByRole('checkbox',{name:'启用识别附件',exact:true}).uncheck()
  await expect(page.getByRole('combobox',{name:'识图模型（覆盖）',exact:true})).toHaveCount(0)
  await page.getByRole('button',{name:'保存并生效',exact:true}).click()
  await expect(page.getByRole('status')).toContainText('已保存并生效')
  await page.goto(app.url+`/#/chat/conversations/${task.id}`)
  await page.getByTestId('attachment-input').setInputFiles({name:'disabled.png',mimeType:'image/png',buffer:Buffer.from(image,'base64')})
  await expect(page.locator('.draft-attachment[data-status=ready]')).toHaveCount(1)
  await expect(page.getByText('当前模型不支持图片；请配置识图模型并启用附件识别工具，或切换聊天模型')).toBeVisible()
  await expect(page.getByTestId('send-message')).toBeDisabled()
  expect(errors).toEqual([])
 }finally{await app.close()}
})

test('inspection input shows four images in order and reports removed files',async({page})=>{
 const app=await fixture({attachmentInspection:true})
 try{
  await page.goto(app.url+'/#/settings/providers')
  await page.getByRole('combobox',{name:'默认识图模型',exact:true}).selectOption('vision')
  await page.getByRole('button',{name:'保存并生效',exact:true}).click()
  await expect(page.getByRole('status')).toContainText('已保存并生效')
  const task=await app.manager.create({title:'多图识别输入',approvalMode:'auto'})
  await page.setViewportSize({width:320,height:900})
  await page.goto(app.url+`/#/chat/conversations/${task.id}`)
  const images=await page.evaluate(()=>['#1d466d','#e5b65b','#608453','#ab4e45'].map(color=>{const c=document.createElement('canvas');c.width=120;c.height=80;const x=c.getContext('2d')!;x.fillStyle=color;x.fillRect(0,0,120,80);return c.toDataURL('image/png').split(',')[1]!}))
  await page.getByTestId('attachment-input').setInputFiles(images.map((image,i)=>({name:`input-${i+1}.png`,mimeType:'image/png',buffer:Buffer.from(image,'base64')})))
  await expect(page.locator('.draft-attachment[data-status=ready]')).toHaveCount(4)
  await page.getByTestId('composer-input').fill('INSPECT_TOOL 比较四张图片。')
  await page.getByTestId('send-message').click()
  await expect(page.getByText('已根据识图结果确认：蓝色背景，金色方块。',{exact:true})).toBeVisible({timeout:60000})
  const call=page.getByTestId('tool-block').filter({has:page.locator('.activity-summary strong',{hasText:'inspect_attachments'})}).first()
  await call.locator('.activity-summary').click()
  const thumbnails=call.getByTestId('attachment-image')
  await expect(thumbnails).toHaveCount(4)
  await expect.poll(()=>call.locator('img').evaluateAll(images=>images.every(image=>(image as HTMLImageElement).naturalWidth>0))).toBe(true)
  const firstSrc=await thumbnails.first().locator('img').getAttribute('src')
  const thirdSrc=await thumbnails.nth(2).locator('img').getAttribute('src')
  await thumbnails.nth(2).click()
  await expect(page.locator('.media-preview-dialog img')).toHaveAttribute('src',thirdSrc!)
  await page.getByRole('button',{name:'关闭图片预览'}).click()
  await call.scrollIntoViewIfNeeded()
  await mkdir(resolve('../.local/attachment-inspection'),{recursive:true})
  await page.screenshot({path:resolve('../.local/attachment-inspection/tool-input-four-320.png')})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth)).toBeLessThanOrEqual(1)
  const path=new URL(firstSrc!,app.url).searchParams.get('path')!
  expect(path).toMatch(/^artifacts\/uploads\/[^/]+\.png$/)
  await unlink(resolve(task.workspace,path))
  await page.reload()
  if(await call.locator('.activity-summary').getAttribute('aria-expanded')==='false')await call.locator('.activity-summary').click()
  await expect(call.getByTestId('attachment-unavailable')).toHaveCount(1)
  await expect(call.getByTestId('attachment-image')).toHaveCount(3)
 }finally{await app.close()}
})
