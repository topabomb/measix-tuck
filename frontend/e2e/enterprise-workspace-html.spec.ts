async function open(page:Page,path:string) {
  const task=await app.manager.create({title:'完整 HTML 预览'})
  await page.goto(app.url+`/#/chat/conversations/${task.id}?ew=1&wide=1&file=${encodeURIComponent(path)}`)
  const panel=page.getByRole('complementary',{name:'企业工作区'})
  await expect(panel.getByRole('tab',{name:path,exact:true})).toBeVisible()
  return {panel,frame:panel.frameLocator('iframe[title="文件静态预览"]')}
}
const gets=(path:string)=>core.requests.filter(request=>request.path===path&&request.method==='GET'&&request.url.includes('/content'))

test('mixed image resources share reads and the link-menu limit does not disable later document links',async({page})=>{
  core.put('mixed.css','body {color:rgb(21, 43, 65)}')
  core.put('destination.txt','later destination remains reachable')
  core.put('mixed.html','<link rel="stylesheet" href="mixed.css"><h1>统一资源预览</h1><img id="blocked" src="https://bad.invalid/mixed.png"><img id="picture" width="240" height="150" src="sample.png"><div id="background" style="width:240px;height:150px;background-image:url(sample.png)"></div>'+Array.from({length:100},(_,index)=>`<a href="hello.txt#part-${index}">链接 ${index}</a>`).join('')+'<a href="destination.txt">末尾链接</a>')
  const external:string[]=[];page.on('request',r=>{if(r.url().includes('bad.invalid'))external.push(r.url())})
  const {panel,frame}=await open(page,'mixed.html')
  await expect(frame.locator('#picture')).toHaveAttribute('data-workspace-state','loaded')
  await expect(frame.locator('#background')).toHaveAttribute('data-workspace-state','loaded')
  await expect(frame.locator('body')).toHaveCSS('color','rgb(21, 43, 65)')
  await expect(frame.locator('#blocked')).not.toHaveAttribute('data-workspace-path')
  expect(gets('sample.png')).toHaveLength(1);expect(gets('mixed.css')).toHaveLength(1)
  await panel.getByRole('button',{name:'重新读取',exact:true}).click()
  await expect(frame.locator('#picture')).toHaveAttribute('data-workspace-state','loaded')
  await expect(frame.locator('#background')).toHaveAttribute('data-workspace-state','loaded')
  // Observe beyond the 250ms preview debounce: reread must not also leave a
  // second preparation scheduled by a competing explicit invocation.
  await page.waitForTimeout(500)
  expect(gets('mixed.css')).toHaveLength(2);expect(gets('sample.png')).toHaveLength(2)
  await panel.getByRole('button',{name:'预览说明与链接',exact:true}).click()
  await expect(panel.getByRole('group',{name:'工作区文件链接'}).getByRole('button')).toHaveCount(100)
  await panel.getByRole('button',{name:'预览说明与链接',exact:true}).press('Escape')
  await frame.getByRole('link',{name:'末尾链接',exact:true}).click()
  await expect(panel.locator('.cm-content')).toContainText('later destination remains reachable')
  expect(external).toEqual([])
})

