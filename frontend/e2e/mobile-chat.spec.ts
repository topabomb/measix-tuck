test('visual viewport contraction preserves the draft and keeps mobile controls above a simulated keyboard',async({page},info)=>{
  const f=await settingsFixture()
  try{
    await page.setViewportSize({width:390,height:760})
    await page.addInitScript(()=>{
      const viewport=new EventTarget() as EventTarget&{height:number;width:number;scale:number;offsetTop:number;offsetLeft:number}
      Object.assign(viewport,{height:760,width:390,scale:1,offsetTop:0,offsetLeft:0})
      Object.defineProperty(window,'visualViewport',{value:viewport})
      Object.assign(window,{simulateKeyboard:(height:number)=>{viewport.height=height;viewport.dispatchEvent(new Event('resize'))}})
    })
    const task=await f.app!.manager.create({title:'可视视口收缩验收'})
    Object.assign(task,{status:'working',activity:{phase:'processing',startedAt:Date.now()},activePlan:{items:Array.from({length:24},(_,i)=>({id:`keyboard-${i}`,text:`键盘场景计划 ${i+1}`,status:i===0?'in-progress':'pending'}))},lastFailure:{code:'keyboard_check',message:'软键盘场景错误提示。'.repeat(16)},queue:Array.from({length:12},(_,i)=>({id:`keyboard-queue-${i}`,prompt:`键盘场景队列 ${i+1}`}))})
    f.app!.store.saveTask(task)
    await page.goto(f.url+`/#/chat/conversations/${task.id}`)
    const input=page.getByTestId('composer-input')
    await input.fill('软键盘场景草稿');await input.focus()
    await page.evaluate(()=>(window as unknown as {simulateKeyboard:(h:number)=>void}).simulateKeyboard(420))
    await expect(page.getByTestId('mode-navigation')).toBeHidden()
    expect((await page.locator('.app-shell').boundingBox())!.height).toBe(420)
    expect((await input.boundingBox())!.y+(await input.boundingBox())!.height).toBeLessThan(420)
    expect(await page.locator('.composer-context').evaluate(el=>el.clientHeight)).toBeLessThanOrEqual(143)
    await page.getByTestId('composer-stop').scrollIntoViewIfNeeded();await expect(page.getByTestId('composer-stop')).toBeInViewport({ratio:1})
    await page.getByTestId('active-plan-summary').scrollIntoViewIfNeeded();await page.getByTestId('active-plan-summary').click()
    await expect(page.getByTestId('active-plan-popover')).toBeVisible()
    await expect(input).toBeInViewport({ratio:1})
    await page.getByRole('button',{name:'对话设置',exact:true}).click()
    const panel=page.getByRole('dialog',{name:'对话设置',exact:true});await expect(panel).toBeVisible();const bounds=(await panel.boundingBox())!
    expect(bounds.y).toBeGreaterThanOrEqual(0);expect(bounds.y+bounds.height).toBeLessThanOrEqual(420)
    await page.keyboard.press('Escape');await expect(input).toHaveValue('软键盘场景草稿')
    await page.screenshot({path:info.outputPath('keyboard-viewport-simulation.png')})
    await page.evaluate(()=>(window as unknown as {simulateKeyboard:(h:number)=>void}).simulateKeyboard(760))
    await expect(page.getByTestId('mode-navigation')).toBeVisible();await expect(input).toHaveValue('软键盘场景草稿')
  }finally{await f.close()}
})
