test('platform resources open unified readonly details and enterprise MCP remains usable',async({page})=>{
  const app=await platformFixture({native:true})
  try {
    await page.goto(app.url+'?inspect=1')
    await expect(page).toHaveURL(/#\/chat\/conversations\/[^/?]+$/)
    await openSettings(page)
    await page.getByRole('navigation',{name:'设置分类'}).getByRole('link',{name:'企业平台',exact:true}).click()
    await page.getByTestId('platform-json').fill(app.material)
    await page.getByTestId('platform-enroll').click()
    const dialog=page.locator('.tuck-platform-modal')
    await expect(dialog.getByRole('button',{name:'模型设置',exact:true})).toHaveCount(0)
    await dialog.getByRole('link',{name:'查看平台模型 GPT-4o Managed',exact:true}).click()
    await expect(page).toHaveURL(/providers\/platform\/.+\/models\/mdl_/)
    await expect(page.getByRole('region',{name:'平台模型详情'})).toContainText('以下平台字段只读')
    await expect(page.getByLabel('上下文窗口',{exact:true})).toHaveValue('240640')
    await expect(page.getByLabel('最大输出',{exact:true})).toHaveValue('32768')
    await expect(page.getByLabel('上下文窗口',{exact:true})).toBeEditable()
    await expect(page.getByLabel('最大输出',{exact:true})).toBeEditable()
    await page.reload()
    await expect(page.getByRole('region',{name:'平台模型详情'})).toBeVisible()
    await page.getByRole('link',{name:'返回提供商',exact:true}).click()
    await expect(page).toHaveURL(/providers\/platform\/prv_[^/]+$/)
    await page.getByRole('navigation',{name:'设置分类'}).getByRole('link',{name:'企业平台',exact:true}).click()
    for(const width of [390,1365]) {
      await page.setViewportSize({width,height:740})
      const rect=(await dialog.boundingBox())!
      expect(rect.x+rect.width).toBeLessThanOrEqual(width)
      expect(await dialog.evaluate(el=>el.scrollWidth-el.clientWidth)).toBeLessThanOrEqual(1)
      await dialog.locator('.model-section').scrollIntoViewIfNeeded()
      await expect(page.getByTestId('mode-chat')).toBeInViewport()
      const card = dialog.locator('.model-section li').first()
      expect((await card.boundingBox())!.height).toBeLessThan(130)
    }
    await closeSettings(page)
    await page.setViewportSize({width:1365,height:900})
    await page.getByTestId('task-model').selectOption(app.snapshot.models[0].modelId)
    await page.getByRole('combobox',{name:'审批模式'}).selectOption('auto')
    await expect(page.getByRole('combobox',{name:'审批模式'})).toHaveValue('auto')
    await expect(page.getByRole('combobox',{name:'审批模式'})).toBeEnabled()
    await page.getByTestId('composer-input').fill('MCP_LOOP')
    await page.getByTestId('composer-input').press('Enter')
    await expect(page.getByTestId('pending-interaction')).toContainText('search_records')
    expect(app.requests.filter(r=>r.body?.method==='tools/call')).toHaveLength(0)
    await page.getByTestId('approve-interaction').click()
    await expect(page.getByTestId('last-turn-reason')).toHaveText('completed')
    expect(app.requests.filter(r=>r.body?.method==='tools/call')).toHaveLength(1)
    const request=app.requests.find(r=>r.path.includes('/mdl_')&&r.body.tools?.length)
    expect(request?.body.max_tokens).toBe(32768)
  }finally{await app.close()}
})
