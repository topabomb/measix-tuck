test('edit enterprise address without enrolling again, including narrow layout and reload', async ({ page }, info) => {
  const app = await platformFixture({ native: true })
  const moved = await platformFixture()
  try {
    await fetch(app.url + '/api/connection/enroll', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ material: app.material }) })
    await page.goto(app.url)
    await expect(page.getByTestId('composer-input')).toBeVisible()
    await openSettings(page)
    await expect(page.getByRole('navigation',{name:'设置分类'}).getByRole('link').first()).toHaveText('企业平台')
    await page.getByRole('navigation',{name:'设置分类'}).getByRole('link',{name:'企业平台',exact:true}).click()
    const dialog = page.locator('.tuck-platform-modal')
    await expect(dialog.getByRole('heading',{name:'企业平台',exact:true})).toBeVisible()
    await dialog.getByRole('button', { name: '修改连接地址' }).click()
    await expect(dialog.getByLabel('企业平台连接地址')).toHaveValue(JSON.parse(app.material).platformUrl)
    await dialog.getByLabel('企业平台连接地址').fill(moved.url + '/invalid')
    await dialog.getByRole('button', { name: '保存并连接' }).click()
    await expect(dialog.getByRole('alert')).toContainText('不含路径')
    await page.setViewportSize({ width: 390, height: 780 })
    await dialog.getByLabel('企业平台连接地址').fill(moved.url)
    expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
    await page.screenshot({ path: info.outputPath('connection-address-mobile.png') })
    await dialog.getByRole('button', { name: '保存并连接' }).click()
    await expect(dialog.getByRole('status')).toHaveText('连接地址已更新，配置已同步')
    await expect(dialog.getByTestId('platform-employee')).toHaveText('员工 · Contract User')
    await page.reload()
    await expect(dialog.locator('.platform-identity')).toContainText(moved.url)
    expect(moved.requests.some(item => item.path.endsWith('/enrollments/exchange'))).toBe(false)
  } finally { await app.close(); await moved.close() }
})

test('paused drafts survive resource sync and allow changing models in the original conversation', async ({page}) => {
  const app = await platformFixture({native:true})
  try {
    const response = await fetch(app.url+'/api/connection/enroll', {method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({material:app.material})})
    expect(response.ok).toBeTruthy()
    const post = async (path:string,body:unknown) => {
      const response = await fetch(app.url+path,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)})
      expect(response.ok).toBeTruthy(); return response.json()
    }
    const task = await post('/api/tasks',{title:'保留排队消息',modelId:app.snapshot.models[0].modelId})
    const readTask = async () => (await (await fetch(app.url+'/api/tasks/'+task.id)).json()).task
    app.app!.manager.get(task.id).queuePaused = true
    await post(`/api/tasks/${task.id}/prompts`,{prompt:'同步后保留这条草稿'})
    const queued = (await readTask()).queue[0].id, nativeId = task.nativeSessionId
    await page.goto(app.url+'?inspect=1')
    await expect(page.getByTestId('task-model')).toHaveValue(app.snapshot.models[0].modelId)
    await openSettings(page)
    await page.getByRole('navigation',{name:'设置分类'}).getByRole('link',{name:'企业平台',exact:true}).click()
    const dialog = page.locator('.tuck-platform-modal')
    await dialog.getByRole('button',{name:'同步配置',exact:true}).click()
    await expect(dialog.getByRole('status')).toHaveText('配置已同步')
    await closeSettings(page)
    await expect(page.getByTestId('task-model')).toBeEnabled()
    await page.getByTestId('task-model').selectOption(app.snapshot.models[1].modelId)
    await expect.poll(async()=>(await readTask()).modelId).toBe(app.snapshot.models[1].modelId)
    await page.reload()
    await expect(page.getByTestId('task-model')).toHaveValue(app.snapshot.models[1].modelId)
    const retained = await readTask()
    expect(retained.nativeSessionId).toBe(nativeId)
    expect(retained.queue[0].id).toBe(queued)
    expect(retained.queuePaused).toBe(true)
    expect(retained.status).toBe('idle')
  } finally { await app.close() }
})

