  const task=await app.manager.create({title:'预览交互与定位'})
  await page.goto(app.url+`/#/chat/conversations/${task.id}?ew=1&file=docs/start.html`)
  const panel=page.getByRole('complementary',{name:'企业工作区'}),frame=panel.frameLocator('iframe[title="文件静态预览"]:visible')
  await frame.getByRole('link',{name:'查看段落',exact:true}).click()
  await expect(panel.getByRole('tab',{name:'target.html',exact:true})).toHaveAttribute('aria-selected','true')
