const remaining = (page: Page) => page.locator('.conversation-vlist').evaluate(el => el.scrollHeight - el.clientHeight - el.scrollTop)

test('conversation navigation closes transient controls without carrying a rename draft to another task', async ({page}) => {
  const app = await fixture()
  try {
    const a = await app.manager.create({title:'原对话 A'})
    const b = await app.manager.create({title:'原对话 B'})
    await page.goto(`${app.url}/#/chat/conversations/${a.id}`)
    await page.getByTestId(`session-${b.id}`).click()
    await expect(page.getByTestId(`session-${b.id}`)).toHaveAttribute('aria-current','page')
    await page.getByTestId('session-menu').click()
    await page.getByRole('button',{name:'重命名',exact:true}).click()
    await page.getByRole('textbox',{name:'对话名称'}).fill('只属于 B 的草稿')
    await page.goBack()
    await expect(page.getByTestId(`session-${a.id}`)).toHaveAttribute('aria-current','page')
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await page.getByTestId('session-menu').click()
    await page.getByRole('button',{name:'重命名',exact:true}).click()
    await expect(page.getByRole('textbox',{name:'对话名称'})).toHaveValue('原对话 A')
    await page.getByRole('button',{name:'取消',exact:true}).click()
    expect(a.title).toBe('原对话 A'); expect(b.title).toBe('原对话 B')
    await page.getByTestId('task-files').click()
    await expect(page.getByRole('dialog')).toBeVisible()
    await page.goForward()
    await expect(page.getByTestId(`session-${b.id}`)).toHaveAttribute('aria-current','page')
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await page.setViewportSize({width:390,height:740})
    await page.getByRole('button',{name:'展开对话列表'}).click()
    await page.getByTestId(`session-${a.id}`).click()
    await expect(page.getByTestId('session-sidebar')).toBeHidden()
    await expect(page.locator('.conversation-shell')).not.toHaveAttribute('inert','')
    await page.getByTestId('composer-input').fill('抽屉关闭后可以输入')
  } finally { await app.close() }
})

test('default conversation bootstrap is shared across mode navigation', async ({page}) => {
  const app = await fixture()
  let release = () => {}
  try {
    const held = new Promise<void>(resolve => release = resolve)
    let posts = 0
    await page.route('**/api/tasks',async route => {
      if (route.request().method() !== 'POST') { await route.continue(); return }
      posts++
      const response = await route.fetch()
      await held
      await route.fulfill({response})
    })
    await page.goto(`${app.url}/#/chat`)
    await expect.poll(() => posts).toBe(1)
    await page.getByTestId('mode-tasks').click()
    await expect(page.getByRole('main',{name:'任务频道'})).toBeVisible()
    await page.getByTestId('mode-chat').click()
    await expect(page.locator('.chat-entry')).toContainText('正在加载对话')
    release()
    await expect(page.getByTestId('composer-input')).toBeVisible()
    expect(posts).toBe(1)
    expect(app.manager.tasks.size).toBe(1)
    await expect(page).toHaveURL(new RegExp(`/chat/conversations/${[...app.manager.tasks.keys()][0]}$`))
  } finally { release(); await app.close() }
})

test('an invalid chat route releases foreground ownership so incoming messages remain unread', async ({page}) => {
  const app = await fixture()
  try {
    const a = await app.manager.create({title:'暂时离开的对话'})
    const b = await app.manager.create({title:'另一对话'})
    await page.goto(`${app.url}/#/chat/conversations/${a.id}`)
    await expect(page.getByTestId('composer-input')).toBeVisible()
    await page.evaluate(id => { location.hash = `/chat/conversations/${id}/messages/99999` }, a.id)
    await expect(page.getByRole('alert')).toHaveText('指定消息不存在')
    app.manager.append(a,{role:'assistant',blocks:[{id:'unread',type:'markdown',data:{markdown:'错误页期间到达的新消息'}}]})
    await page.evaluate(id => { location.hash = `/chat/conversations/${id}` }, b.id)
    await expect(page.getByTestId(`session-${a.id}`)).toHaveClass(/unread/)
    await page.getByTestId(`session-${a.id}`).click()
    await expect(page.getByText('错误页期间到达的新消息',{exact:true})).toBeVisible()
    await expect(page.getByTestId(`session-${a.id}`)).not.toHaveClass(/unread/)
  } finally { await app.close() }
})

