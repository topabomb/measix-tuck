test('an open summary follows internal sidebar resizing without a window resize',async({page})=>{
  const app=await fixture()
  try{
    await app.manager.create({title:'摘要边界重排'})
    await page.setViewportSize({width:1365,height:800})
    await page.goto(app.url)
    await page.locator('.session-summary > button').first().click()
    const panel=page.getByRole('dialog',{name:'会话统计',exact:true})
    await expect(panel).toBeVisible()
    const before=(await panel.boundingBox())!.x
    const resize=page.getByRole('separator',{name:'调整对话列表宽度'})
    for(let i=0;i<3;i++)await resize.press('ArrowRight')
    await expect(panel).toBeVisible()
    await expect.poll(async()=>Math.round((await panel.boundingBox())!.x-before)).toBe(60)
    const boundary=(await page.locator('[data-summary-boundary]').boundingBox())!
    expect((await panel.boundingBox())!.x).toBeGreaterThanOrEqual(boundary.x+11)
    await panel.getByRole('button',{name:'关闭摘要'}).click()
    await expect(panel).toBeHidden()
  }finally{await app.close()}
})

test('appearance is a page and reports in-flight theme import results', async ({page}) => {
  const app = await fixture()
  let release = () => {}
  try {
    await app.manager.create({title:'主题请求状态'})
    await page.goto(app.url)
    await openSettings(page)
    await page.getByRole('navigation',{name:'设置分类'}).getByRole('link',{name:'外观',exact:true}).click()
    const dialog = page.getByRole('region',{name:'外观设置',exact:true})
    await dialog.getByText('加载外部主题',{exact:true}).click()
    const gate = new Promise<void>(resolve=>{release=resolve})
    await page.route('**/review-theme.json',async route=>{await gate;await route.fulfill({status:503,body:'temporary unavailable'})})
    await dialog.getByRole('textbox',{name:'主题地址'}).fill(app.url+'/review-theme.json')
    await dialog.getByRole('button',{name:'加载',exact:true}).click()
    await expect(dialog.getByRole('button',{name:'加载中…',exact:true})).toBeDisabled()
    await page.mouse.click(2,2); await page.keyboard.press('Escape')
    await expect(dialog).toBeVisible()
    release()
    await expect(dialog.getByRole('alert')).toContainText('503')
    await expect(dialog.getByRole('button',{name:'加载',exact:true})).toBeEnabled()
    await closeSettings(page)
    await expect(dialog).toHaveCount(0)
  } finally { release(); await app.close() }
})

test('lightweight surfaces dismiss outside, edited forms stay, and rename persists through native Agent and reload', async ({page}) => {
  const app = await fixture()
  try {
    const task = await app.manager.create({title:'界面交互验收'})
    await page.goto(app.url)
    const menu = page.getByTestId('session-menu')
    await menu.click()
    await expect(page.getByRole('button',{name:'重命名',exact:true})).toBeVisible()
    await page.getByTestId('composer-input').click()
    await expect(page.getByRole('button',{name:'重命名',exact:true})).toBeHidden()
    await menu.click(); await page.keyboard.press('Escape')
    await expect(menu).toBeFocused()
    await page.locator('.session-summary > button').first().click()
    await expect(page.getByRole('dialog',{name:'会话统计'})).toBeVisible()
    await page.getByTestId('composer-input').click()
    await expect(page.getByRole('dialog',{name:'会话统计'})).toBeHidden()
    await page.getByTestId('task-files').click()
    await expect(page.getByRole('dialog',{name:'任务产物',exact:true})).toBeVisible()
    await page.mouse.click(2,2)
    await expect(page.getByRole('dialog',{name:'任务产物',exact:true})).toBeHidden()
    await menu.click(); await page.getByRole('button',{name:'重命名',exact:true}).click()
    await page.getByLabel('对话名称').fill('新的对话名称')
    await page.mouse.click(2,2)
    await expect(page.getByRole('dialog',{name:'重命名对话'})).toBeVisible()
    await page.getByRole('button',{name:'保存',exact:true}).click()
    await expect(page.getByRole('dialog',{name:'重命名对话'})).toHaveCount(0)
    await expect(page.getByTestId('session-navigation')).toContainText('新的对话名称')
    expect((await app.docker.request(`/api/sessions/${task.nativeSessionId}`)).title).toBe('新的对话名称')
    expect(app.store.tasks().find(entry=>entry.id===task.id)?.title).toBe('新的对话名称')
    await page.reload()
    await expect(page.getByRole('link',{name:'新的对话名称 · 空闲',exact:true})).toBeVisible()
    await menu.click(); await page.getByTestId('diagnostics-open').click()
    const panel = page.getByRole('complementary',{name:'运行详情'})
    const heading = panel.locator('.diagnostics-head')
    const top = (await heading.boundingBox())!.y
    const bottoms = await page.locator('.sidebar-head,.conversation-header,.diagnostics-head').evaluateAll(els=>els.map(el=>el.getBoundingClientRect().bottom))
    expect(Math.max(...bottoms)-Math.min(...bottoms)).toBeLessThanOrEqual(1)
    await panel.locator('.diagnostics-body').evaluate(el=>{el.scrollTop=300})
    expect((await heading.boundingBox())!.y).toBe(top)
    expect((await panel.locator('.diagnostics-body').boundingBox())!.y).toBeGreaterThanOrEqual(top+(await heading.boundingBox())!.height)
    await expect(panel.getByRole('button',{name:'Close diagnostics'})).toBeInViewport()
  } finally { await app.close() }
})

test('archive rows, header actions and primary hover share theme colors and stable geometry', async ({page}) => {
  const app = await fixture()
  try {
    const archived = await app.manager.create({title:'很长的已归档对话名称'.repeat(6)})
    archived.archived = true; app.store.saveTask(archived)
    const task = await app.manager.create({title:'主题验收'})
    task.forkedFrom = {id:archived.id,title:archived.title,userMessageIndex:0}; app.store.saveTask(task)
    app.manager.submit(task.id, '界面验证')
    await until(()=>task.turnCount===1 && !app.manager.runs.has(task.id))
    app.manager.append(task,{role:'assistant',blocks:[{id:'tool',type:'tool-call',data:{name:'read_file',callId:'visual',status:'success',input:{}}}]})
    await page.goto(app.url)
    await expect(page.locator('.agent-activity .activity-status.success')).toHaveAttribute('aria-label','完成')
    expect(await page.locator('.run-status .activity-status svg').innerHTML()).toBe(await page.locator(`a[data-session-id="${task.id}"] .activity-status svg`).innerHTML())
    for (const theme of ['墨蓝','苔灰','暖砂','炭棕','曜黑（高对比）','石墨']) {
      await openSettings(page)
      await page.getByRole('navigation',{name:'设置分类'}).getByRole('link',{name:'外观',exact:true}).click()
      await page.getByRole('button',{name:`${theme}`,exact:true}).click()
      await closeSettings(page)
      for (const expanded of [true,false]) {
        await page.locator('.activity-summary').click()
        await expect(page.locator('.activity-summary')).toHaveAttribute('aria-expanded',String(expanded))
        const delta = await page.locator('.activity-summary').evaluate(el=>{const status=el.querySelector('.activity-status svg')!.getBoundingClientRect(),arrow=el.querySelector('.disclosure-icon svg')!.getBoundingClientRect();return Math.abs(status.y+status.height/2-arrow.y-arrow.height/2)})
        expect(delta).toBeLessThan(1)
      }
      await page.locator('.archived-sessions > summary').click()
      const restore = page.getByRole('button',{name:`恢复 ${archived.title}`,exact:true})
      await expect(restore).toBeVisible()
      const row = await restore.evaluate(el=>{const style=getComputedStyle(el), title=el.querySelector('.archive-title')!;return {font:style.fontSize,border:style.borderWidth,overflow:title.scrollWidth>title.clientWidth,height:el.getBoundingClientRect().height}})
      expect(row).toMatchObject({border:'0px',overflow:true}); expect(row.height).toBeLessThanOrEqual(36)
      await restore.hover()
      await restore.focus(); await page.keyboard.press('Tab'); await page.keyboard.press('Shift+Tab')
      expect(await restore.evaluate(el=>getComputedStyle(el).outlineStyle)).toBe('solid')
      await page.locator('.archived-sessions > summary').click()
      const actions = await page.locator('.conversation-header .reference-header-action').evaluateAll(elements=>elements.map(el=>{const box=el.getBoundingClientRect(),svg=el.querySelector('svg')!.getBoundingClientRect(),label=el.querySelector('span')!.getBoundingClientRect();return {height:box.height,offset:Math.abs(svg.y+svg.height/2-label.y-label.height/2)}}))
      expect(actions).toHaveLength(3); expect(actions.every(item=>item.height===30 && item.offset<1)).toBe(true)
      await page.getByTestId('session-menu').click(); await page.getByRole('button',{name:'创建分支',exact:true}).click()
      const submit=page.locator('dialog button[type=submit]')
      await expect(submit).toBeEnabled()
      const color=await submit.evaluate(el=>({bg:getComputedStyle(el).backgroundColor,fg:getComputedStyle(el).color}))
      await submit.hover()
      expect(await submit.evaluate(el=>({bg:getComputedStyle(el).backgroundColor,fg:getComputedStyle(el).color}))).toEqual(color)
      await page.keyboard.press('Escape')
    }
    await page.locator('.archived-sessions > summary').click()
    await page.getByRole('button',{name:`恢复 ${archived.title}`,exact:true}).click()
    await expect(page.locator('.archived-sessions')).toHaveCount(0)
    expect(archived.archived).toBe(false)
    await page.setViewportSize({width:390,height:740})
    await page.getByTestId('session-menu').click()
    await expect(page.getByRole('button',{name:'产物',exact:true})).toBeInViewport()
    expect(await page.evaluate(()=>document.body.scrollWidth-innerWidth)).toBeLessThanOrEqual(1)
  } finally { await app.close() }
})
