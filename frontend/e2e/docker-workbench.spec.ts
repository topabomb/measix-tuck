import { test, expect } from '@playwright/test'
import { fixture } from '../../tests/fixtures/fixture.mjs'

let app: Awaited<ReturnType<typeof fixture>>
test.beforeAll(async () => { app = await fixture() })
test.afterAll(async () => { await app.close() })

test('real native runtime through the UI: interaction, child, files, active reload, stop and archive', async ({ page }) => {
  test.setTimeout(90000)
  const errors: string[] = []
  page.on('pageerror', error => { if (!error.message.includes('ResizeObserver')) errors.push(error.message) })
  await page.goto(app.url + '?inspect=1')
  await expect(page.getByTestId('active-session-id')).toBeVisible()
  const id = await page.getByTestId('active-session-id').textContent()
  await page.getByTestId('composer-input').fill('FULL_LOOP')
  await page.getByTestId('composer-input').press('Enter')
  await expect(page.getByTestId('pending-interaction')).toContainText('报告标题')
  await page.reload()
  await expect(page.getByTestId('pending-interaction')).toContainText('报告标题')
  await page.getByTestId('question-answer').fill('实际 UI 验收')
  await page.getByTestId('approve-interaction').click()
  await expect(page.getByTestId('pending-interaction')).toContainText('write_file')
  await page.getByTestId('approve-interaction').click()
  await expect(page.getByTestId('pending-interaction')).toContainText('shell')
  await page.getByTestId('approve-interaction').click()
  await expect(page.getByTestId('last-turn-reason')).toHaveText('completed', { timeout: 30000 })
  await expect(page.getByTestId('delegation-block')).toBeVisible()
  await page.getByTestId('delegation-block').getByRole('button').click()
  await page.locator('[data-child-session-id]').first().click()
  await expect(page.getByTestId('active-session-id')).not.toHaveText(id!)
  await expect(page.getByText('子 Agent 已独立完成检查。')).toBeVisible()
  await page.getByTestId('parent-session-link').click()
  await expect(page.getByTestId('active-session-id')).toHaveText(id!)
  await page.getByTestId('task-files').click()
  await page.locator('.tuck-file-row').filter({ hasText: 'report.md' }).click()
  await expect(page.locator('.tuck-editor textarea')).toHaveValue(/Docker Agent/)
  await page.getByRole('button', { name: '关闭文件预览', exact: true }).click()
  await page.getByRole('dialog', { name: '任务产物', exact: true }).getByRole('button', { name: '关闭文件', exact: true }).click()
  await page.reload()
  await expect(page.getByTestId('last-turn-reason')).toHaveText('completed')
  await expect(page.getByTestId('playback-mode')).toHaveText('docker-agent')
  await page.getByTestId('composer-input').fill('SLOW')
  await page.getByTestId('composer-input').press('Enter')
  await expect(page.getByTestId('composer-stop')).toBeVisible()
  await page.reload()
  await expect(page.getByTestId('composer-stop')).toBeVisible()
  await page.getByTestId('composer-stop').click()
  await expect(page.getByTestId('last-turn-reason')).toHaveText('interrupted')
  await page.getByTestId('session-menu').click()
  await page.getByTestId('task-archive').click()
  await expect(page.getByTestId('active-session-id')).not.toHaveText(id!)
    await expect(page.locator('.archived-sessions > summary')).toContainText('已归档')
    await expect(page.locator('.archive-count')).toHaveText('1')
  await page.locator('.archived-sessions > summary').click()
  await page.getByRole('button', { name: '恢复 新任务' }).click()
  await expect(page.getByTestId(`session-${id}`)).toBeVisible()
  expect(errors).toEqual([])
})
