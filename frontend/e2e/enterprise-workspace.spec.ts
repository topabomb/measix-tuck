test('settings channel return recovers a failed runtime refresh without discarding workspace drafts',async({page})=>{
  const task=await app.manager.create({title:'连接刷新失败保留草稿'})
  const errors:string[]=[]
  page.on('pageerror',error=>errors.push(error.message))
  await page.goto(app.url+`/#/chat/conversations/${task.id}?ew=1`)
  const panel=page.getByRole('complementary',{name:'企业工作区'})
  await panel.getByRole('option',{name:/hello\.txt/}).dblclick()
  const editor=panel.locator('.ew-document:visible .cm-content')
  await expect(editor).toBeVisible()
  await editor.fill('draft retained after failed runtime refresh')
  const original=core.files.get('hello.txt')?.toString()
  const runtime=await (await page.request.get(app.url+'/api/runtime')).json()
  // Let the real settings UI emit changed after a successful configuration request.
  // The following runtime refresh, rather than the configuration request, fails.
  await page.route('**/api/connection/enroll',route=>route.fulfill({json:runtime.connection}))
  let failures=0
  await page.route('**/api/runtime',async route=>{failures++;await route.fulfill({status:503,json:{error:'runtime refresh unavailable'}})},{times:1})
  await page.getByTestId('mode-settings').click();await page.getByRole('navigation',{name:'设置快捷菜单'}).getByRole('link',{name:'设置',exact:true}).click()
  const leave=page.getByRole('dialog',{name:'企业工作区有未保存修改，仍要离开当前频道？草稿将保留至本页面关闭。',exact:true})
  await expect(leave).toBeVisible();await leave.getByRole('button',{name:'取消',exact:true}).click();await expect(editor).toContainText('draft retained after failed runtime refresh')
  await page.getByTestId('mode-settings').click();await page.getByRole('navigation',{name:'设置快捷菜单'}).getByRole('link',{name:'设置',exact:true}).click();await leave.getByRole('button',{name:'确定',exact:true}).click();await expect(page.locator('main.settings-mode')).toBeVisible()
  await page.getByRole('navigation',{name:'设置分类'}).getByRole('link',{name:'企业平台',exact:true}).click()
  await page.getByText('更换企业平台接入',{exact:true}).click()
  await page.getByTestId('platform-json').fill('{"fixture":"connection-change"}')
  await page.getByTestId('platform-enroll').click()
  const settings=page.locator('.tuck-platform-modal')
  await expect(settings.getByRole('status')).toHaveText('企业平台已接入')
  await expect.poll(()=>failures).toBe(1)
  await closeSettings(page)
  await expect(panel.getByRole('button',{name:'保存',exact:true})).toBeEnabled()
  await expect(panel.getByRole('alert')).toHaveCount(0)
  await expect(editor).toContainText('draft retained after failed runtime refresh')
  expect(core.files.get('hello.txt')?.toString()).toBe(original)
  expect(failures).toBe(1)
  expect(errors).toEqual([])
})

