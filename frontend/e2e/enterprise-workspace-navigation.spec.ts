test('sorting directions retain folder grouping and restore from the URL',async({page})=>{
  core.files.clear();core.directories.clear()
  for(const path of ['', 'z-folder', 'a-folder'])core.directories.add(path)
  core.put('a.txt','aaaa');core.put('b.txt','bb');core.put('c.txt','c')
  const dates:Record<string,string>={'a.txt':'2024-01-01T00:00:00Z','b.txt':'2026-01-01T00:00:00Z','c.txt':'2025-01-01T00:00:00Z'}
  await page.route('**/api/enterprise-workspace/files?**',async route=>{
    const response=await route.fetch(),body=await response.json()
    if(Array.isArray(body.entries))for(const entry of body.entries)if(dates[entry.path])entry.modifiedAt=dates[entry.path]
    await route.fulfill({response,json:body})
  })
  const panel=await open(page)
  const paths=()=>panel.getByRole('listbox').getByRole('option').evaluateAll(nodes=>nodes.map(node=>node.getAttribute('title')))
  const files=async()=>(await paths()).filter(path=>path?.endsWith('.txt'))
  const query=()=>new URLSearchParams(page.url().split('?')[1])
  await expect.poll(paths).toEqual(['a-folder','z-folder','a.txt','b.txt','c.txt'])
  await panel.getByRole('button',{name:'显示选项',exact:true}).click()
  await expect(panel.getByRole('button',{name:'升序',exact:true})).toHaveAttribute('aria-pressed','true')
  await panel.getByRole('button',{name:'降序',exact:true}).click()
  await expect.poll(paths).toEqual(['z-folder','a-folder','c.txt','b.txt','a.txt'])
  expect(query().get('order')).toBe('desc')
  await panel.getByLabel('文件排序',{exact:true}).selectOption('size')
  await expect(panel.getByRole('button',{name:'降序',exact:true})).toHaveAttribute('aria-pressed','true')
  await expect.poll(files).toEqual(['a.txt','b.txt','c.txt'])
  expect(query().has('order')).toBe(false)
  await panel.getByRole('button',{name:'升序',exact:true}).click()
  await expect.poll(paths).toEqual(['a-folder','z-folder','c.txt','b.txt','a.txt'])
  await page.reload()
  await expect.poll(paths).toEqual(['a-folder','z-folder','c.txt','b.txt','a.txt'])
  expect(query().get('sort')).toBe('size');expect(query().get('order')).toBe('asc')
  await panel.getByRole('button',{name:'显示选项',exact:true}).click()
  await expect(panel.getByRole('button',{name:'升序',exact:true})).toHaveAttribute('aria-pressed','true')
  await panel.getByLabel('文件排序',{exact:true}).selectOption('date')
  await expect(panel.getByRole('button',{name:'降序',exact:true})).toHaveAttribute('aria-pressed','true')
  await expect.poll(files).toEqual(['b.txt','c.txt','a.txt'])
  expect(query().has('order')).toBe(false)
  await panel.getByRole('button',{name:'升序',exact:true}).click()
  await expect.poll(paths).toEqual(['a-folder','z-folder','a.txt','c.txt','b.txt'])
  await panel.getByLabel('文件排序',{exact:true}).selectOption('name')
  await expect(panel.getByRole('button',{name:'升序',exact:true})).toHaveAttribute('aria-pressed','true')
  await expect.poll(paths).toEqual(['a-folder','z-folder','a.txt','b.txt','c.txt'])
})
