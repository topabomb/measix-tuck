import { expect, test } from '@playwright/test'
import { fixture, until } from '../../tests/fixtures/fixture.mjs'

for (const width of [1365, 390]) test(`retention confirmation, keep and restore at ${width}px`, async ({ page, context }, info) => {
  const app = await fixture()
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  try {
    const task = await app.manager.create({ title: '保留与恢复验证', approvalMode: 'auto' })
    app.manager.submit(task.id, '保留的历史消息')
    await until(() => app.manager.get(task.id).lastTurnReason === 'completed' && !app.manager.runs.has(task.id))
    await page.setViewportSize({ width, height: 844 })
    await page.goto(`${app.url}/#/chat/conversations/${task.id}`)
    await page.getByTestId('session-menu').click()
    await page.getByRole('button', { name: '保留对话', exact: true }).click()
    await expect(page.getByRole('button', { name: '取消保留', exact: true })).toBeVisible()
    expect(app.manager.get(task.id).lifecycle?.keep).toBe(true)
    await page.getByTestId('task-archive').click()
    if (width < 760) await page.getByRole('button', { name: '展开对话列表', exact: true }).click()
    await page.locator('.archived-sessions > summary').click()
    const archived = page.locator('.retention-status').filter({ hasText: '归档于' })
    await expect(archived).toContainText('已标记保留')

    const settings = await context.newPage()
    await settings.setViewportSize({ width, height: 844 })
    await settings.goto(`${app.url}/#/settings/orchestration`)
    const form = settings.locator('.retention-settings')
    const before = await (await settings.request.get(`${app.url}/api/settings/retention`)).json()
    await expect(form).not.toContainText('临时执行记录')
    await expect(form).not.toContainText('纳管')
    await expect(form).toContainText('删除整个文件夹及其中全部文件')
    await expect(form).toContainText('此选项关闭时创建的文件夹')
    await form.getByLabel('归档到期后自动永久删除', { exact: true }).check()
    await form.getByLabel('删除对话时清理自动工作文件夹', { exact: true }).check()
    await form.getByRole('button', { name: '保存设置', exact: true }).click()
    const confirm = settings.getByRole('dialog', { name: '确认自动删除', exact: true })
    await expect(confirm).toContainText('永久删除无法撤销')
    await expect(confirm).toContainText('最后一个共用对话删除后')
    await confirm.getByRole('button', { name: '取消', exact: true }).click()
    const cancelled = await (await settings.request.get(`${app.url}/api/settings/retention`)).json()
    expect(cancelled.applied.conversations.autoDelete).toBe(false)
    expect(cancelled.applied.managedWorkspaces.autoCleanup).toBe(false)
    await form.getByRole('button', { name: '保存设置', exact: true }).click()
    await confirm.getByRole('button', { name: '确认保存', exact: true }).click()
    await expect(form.getByRole('status')).toHaveText('归档与清理设置已生效。')
    const after = await (await settings.request.get(`${app.url}/api/settings/retention`)).json()
    expect(after.retention.temporaryRuns).toEqual(before.retention.temporaryRuns)
    expect(after.applied.managedWorkspaces.autoCleanup).toBe(true)
    expect(await form.getByLabel('长时间未使用时自动归档', { exact: true }).evaluate(el => getComputedStyle(el.parentElement!).display)).toBe('flex')
    await form.getByRole('heading', { name: '归档与保留', exact: true }).scrollIntoViewIfNeeded()
    await settings.screenshot({ path: info.outputPath(`retention-settings-${width}.png`) })
    expect(await settings.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
    await archived.getByRole('button', { name: '取消保留', exact: true }).click()
    await expect(archived).toContainText('预计删除')
    await page.screenshot({ path: info.outputPath(`retention-archived-${width}.png`) })
    await page.request.post(`${app.url}/api/tasks/${task.id}/archive`, { data: { archived: false } })
    await page.goto(`${app.url}/#/chat/conversations/${task.id}`)
    await page.getByTestId('session-menu').click()
    await expect(page.locator('.retention-status').filter({ hasText: '预计归档' })).toBeVisible()
    const resumed = await page.request.post(`${app.url}/api/tasks/${task.id}/prompts`, { data: { prompt: '继续保留的历史消息' } })
    expect(resumed.status()).toBe(202)
    await until(() => app.manager.get(task.id).turnCount === 2 && app.manager.get(task.id).lastTurnReason === 'completed' && !app.manager.runs.has(task.id))
    expect((await (await page.request.get(`${app.url}/api/tasks/${task.id}/messages?start=0&count=64`)).json()).messages.length).toBeGreaterThan(0)
    expect(errors.filter(message => !message.includes('ResizeObserver'))).toEqual([])
    await settings.close()
  } finally { await app.close() }
})
