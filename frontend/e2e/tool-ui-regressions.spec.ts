import {test,expect} from '@playwright/test'
import {fixture} from '../../tests/fixtures/fixture.mjs'

test('image prompt copy works inside a modal when Clipboard API is denied',async({page,context},info)=>{
 const app=await fixture()
 try{
  const task=await app.manager.create({title:'提示词复制回退'})
  const prompt='A blue square.\nKeep the original composition.'
  const png='iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII='
  app.store.saveMessage(task.id,{id:'prompt-copy',index:0,turnId:'preview',role:'assistant',blocks:[{id:'image',type:'attachments',data:{provenance:{origin:'tool-output',toolName:'generate_images',prompt},items:[{id:'image',kind:'image',name:'generated.png',mimeType:'image/png',src:'data:image/png;base64,'+png}]}}]})
  task.logicalCount=1;app.store.saveTask(task)
  await context.grantPermissions(['clipboard-read','clipboard-write'],{origin:app.url})
  await page.setViewportSize({width:320,height:900})
  await page.goto(app.url+`/#/chat/conversations/${task.id}`)
  await page.getByTestId('attachment-image').click()
  await expect(page.getByRole('textbox',{name:'生图提示词内容'})).toHaveValue(prompt)
  await page.evaluate(async()=>{
   await navigator.clipboard.writeText('unchanged clipboard')
   Object.defineProperty(navigator.clipboard,'writeText',{value:()=>Promise.reject(new DOMException('Clipboard API denied','NotAllowedError'))})
  })
  await page.getByRole('button',{name:'复制提示词',exact:true}).click()
  await expect(page.getByRole('button',{name:'已复制',exact:true})).toBeFocused()
  expect((await page.evaluate(()=>navigator.clipboard.readText())).replace(/\r\n/g,'\n')).toBe(prompt)
  await page.screenshot({path:info.outputPath('prompt-copy-fallback-320.png')})
 }finally{await app.close()}
})

test('image resource rename commits once without stealing another resource reference and respects Agent protection',async({page})=>{
 test.setTimeout(120000)
 const app=await fixture()
 try{
  await page.goto(app.url+'/#/settings/providers')
  for(const id of ['image_a','image_ab']){
   await page.getByRole('button',{name:'添加生图资源',exact:true}).click()
   const card=page.locator('.image-generator-card').last()
   await card.getByLabel('生图资源名称',{exact:true}).fill(id)
   await card.getByLabel('生图资源标识',{exact:true}).fill(id)
   await card.getByLabel('生图上游模型',{exact:true}).fill('synthetic-image')
  }
  const global=page.getByLabel('默认生图资源',{exact:true})
  await global.selectOption('local:image_ab')
  await page.getByRole('button',{name:'保存并生效',exact:true}).click()
  await expect(page.getByRole('status')).toContainText('已保存并生效')
  await page.goto(app.url+'/#/settings/agents/root/tools/tuck')
  await page.getByLabel('生图资源（覆盖）',{exact:true}).selectOption('local:image_ab')
  await page.getByRole('button',{name:'保存并生效',exact:true}).click()
  await expect(page.getByRole('status')).toContainText('已保存并生效')
  await page.goto(app.url+'/#/settings/providers')
  const first=page.locator('.image-generator-card').first().getByLabel('生图资源标识',{exact:true})
  await first.focus();await first.press('End');await first.pressSequentially('b')
  await expect(first).toHaveValue('image_ab')
  await expect(global).toHaveValue('local:image_ab')
  await first.pressSequentially('c');await first.press('Tab')
  await expect(first).toHaveValue('image_abc')
  await expect(global).toHaveValue('local:image_ab')
  await page.getByRole('button',{name:'保存并生效',exact:true}).click()
  await expect(page.getByRole('status')).toContainText('已保存并生效')
  await page.goto(app.url+'/#/settings/agents/root/tools/tuck')
  await expect(page.getByLabel('生图资源（覆盖）',{exact:true})).toHaveValue('local:image_ab')
  await page.goto(app.url+'/#/settings/providers')
  const secondCard=page.locator('.image-generator-card').nth(1)
  const second=secondCard.getByLabel('生图资源标识',{exact:true})
  await second.fill('image_ab_renamed');await second.press('Tab')
  await expect(global).toHaveValue('local:image_ab_renamed')
  await second.fill('image_abc');await second.press('Tab')
  await expect(second).toHaveValue('image_ab_renamed')
  await expect(secondCard.getByRole('alert')).toContainText('此生图资源标识已存在，已保留原标识')
  await second.fill('invalid name');await second.press('Tab')
  await expect(second).toHaveValue('image_ab_renamed')
  await expect(secondCard.getByRole('alert')).toContainText('已保留原标识')
  await page.getByRole('button',{name:'保存并生效',exact:true}).click()
  await expect(page.getByRole('status')).toContainText('已保存并生效')
  await page.goto(app.url+'/#/settings/agents/root/tools/tuck')
  await expect(page.getByLabel('生图资源（覆盖）',{exact:true})).toHaveValue('local:image_ab_renamed')
  await page.goto(app.url+'/#/settings/protection')
  await page.getByLabel('保护密码',{exact:true}).fill('synthetic-tool-protection')
  await page.getByLabel('确认新密码',{exact:true}).fill('synthetic-tool-protection')
  for(const name of ['提供商与模型','MCP','企业平台','编排'])await page.getByRole('checkbox',{name:new RegExp('^'+name)}).uncheck()
  await page.getByRole('checkbox',{name:/^Agent/}).check()
  await page.getByRole('button',{name:'保存保护设置',exact:true}).click()
  await expect(page.getByRole('heading',{name:'此配置已锁定'})).toBeVisible()
  await page.goto(app.url+'/#/settings/providers')
  await expect(first).toBeDisabled();await expect(second).toBeDisabled()
  await expect(global).toHaveValue('local:image_ab_renamed')
  await secondCard.getByLabel('生图资源名称',{exact:true}).fill('可编辑名称')
  const saved=page.waitForRequest(r=>r.url().endsWith('/api/settings/runtime')&&r.method()==='PUT')
  await page.getByRole('button',{name:'保存并生效',exact:true}).click()
  expect((await saved).postDataJSON().config).not.toHaveProperty('agents')
  await expect(page.getByRole('status')).toContainText('已保存并生效')
  await page.reload();await expect(second).toHaveValue('image_ab_renamed');await expect(second).toBeDisabled()
 }finally{await app.close()}
})
